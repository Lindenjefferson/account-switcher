#!/usr/bin/env bash
# Shared functions for the scripts in ~/.claude-accounts on macOS and Linux.
# Counterpart of comum.ps1 on Windows: every account has its own config folder (CLAUDE_CONFIG_DIR)
# with its own login; everything else is a symlink to the master folder ~/.claude.
# This file only defines functions and variables (use it with "source"). It is compatible with the
# bash 3.2 that ships with macOS: no associative arrays, no mapfile, no ${var,,}. Needs jq and curl.
# The scripts deliberately avoid "set -e" and "set -u": on bash 3.2, "set -u" breaks on empty arrays.

# shellcheck disable=SC2034  # the globals below are read by the scripts that source this file
if [ -z "${HOME:-}" ] || [ ! -d "$HOME" ]; then
    echo "HOME is not set or is not a directory" >&2
    return 1 2>/dev/null || exit 1
fi

BASE_DIR="$HOME/.claude-accounts"
MASTER_DIR="$HOME/.claude"
MASTER_STATE="$HOME/.claude.json"            # .claude.json of the account that lives in the master folder
SEP=$'\037'                                   # field separator (not whitespace, so empty fields are kept)

# What is shared with the master folder. Login (.credentials.json), .claude.json, cache, state,
# shell-snapshots, backups etc. stay separate per account.
SHARED_FILES=(settings.json history.jsonl CLAUDE.md keybindings.json)
SHARED_DIRS=(projects file-history session-env sessions skills plugins dev-mods agents
             commands output-styles hooks rules)

# Keys of ~/.claude.json copied into a new account (configuration, not account data).
SEED_KEYS=(mcpServers projects githubRepoPaths hasCompletedOnboarding lastOnboardingVersion
           installMethod autoUpdates autoUpdatesProtectedForNative claudeInChromeDefaultEnabled
           hasCompletedClaudeInChromeOnboarding cachedChromeExtensionInstalled)

MARK_BEGIN='<!-- account-switcher:begin -->'
MARK_END='<!-- account-switcher:end -->'
MARK_STATUSLINE='.claude-accounts/statusline.sh'
MARK_PATH_BEGIN='# >>> account-switcher >>>'
MARK_PATH_END='# <<< account-switcher <<<'
MARK_WRAPPER='# account-switcher: command generated by install.sh'

MSG_INVALID_SETTINGS='invalid settings.json (broken JSON): left untouched; fix the file and run setup-accounts.sh'

# ---------------------------------------------------------------- messages (always on stderr)

_color_msg() {
    local color=$1; shift
    if [ -t 2 ] && [ -z "${NO_COLOR:-}" ]; then printf '\033[%sm%s\033[0m\n' "$color" "$*" >&2
    else printf '%s\n' "$*" >&2; fi
}
msg_gray()   { _color_msg 90 "$@"; }
msg_yellow() { _color_msg 33 "$@"; }
msg_red()    { _color_msg 31 "$@"; }

# ---------------------------------------------------------------- claude

# First executable "claude" on PATH that is not one of ours (BASE_DIR/bin); else ~/.local/bin/claude.
find_claude() {
    local dir IFS=:
    for dir in $PATH; do
        [ -n "$dir" ] || continue
        case "$dir/" in "$BASE_DIR"/*) continue ;; esac
        if [ -f "$dir/claude" ] && [ -x "$dir/claude" ]; then printf '%s' "$dir/claude"; return 0; fi
    done
    if [ -x "$HOME/.local/bin/claude" ]; then printf '%s' "$HOME/.local/bin/claude"; return 0; fi
    return 1
}
CLAUDE=$(find_claude) || CLAUDE="$HOME/.local/bin/claude"

# ---------------------------------------------------------------- accounts.json

# Shared jq definitions: ISO 8601 date (with fraction and offset) or Unix seconds to epoch seconds.
JQ_DEFS='
def iso:
  capture("^(?<d>[0-9]{4}-[0-9]{2}-[0-9]{2})[T ](?<t>[0-9]{2}:[0-9]{2}:[0-9]{2})(\\.[0-9]+)?(?<z>Z|[+-][0-9]{2}:?[0-9]{2})?$") as $m
  | (($m.d + "T" + $m.t + "Z") | fromdateiso8601) as $e
  | (($m.z // "Z") as $z
     | if $z == "Z" then 0
       else (($z[1:3] | tonumber) * 3600 + ($z[-2:] | tonumber) * 60) * (if $z[0:1] == "-" then -1 else 1 end) end) as $off
  | $e - $off;
def ep:
  if . == null then null
  elif type == "number" then floor
  elif type == "string" then (try iso catch null)
  else null end;
'

# Flattens accounts.json: a header line (main, default, publish, command, chrome, warn) and one line per
# account (name, email, folder, rc). Only one account uses the master folder: the one that has "dir"
# or, if none has it, the main account.
JQ_ACCOUNTS='
def str(x): x | if type == "string" and length > 0 then . else null end;
def expand_home: if . == "~" then $home elif startswith("~/") then $home + .[1:] else . end;
(.accounts | with_entries(.value |= if type == "object" then . else {} end)) as $accounts
| (str(.main) // str(.default) // "") as $main
| ([$accounts[] | str(.dir)] | map(select(. != null)) | length > 0) as $any_dir
| ([ $main,
     (str(.default) // $main),
     (str(.publish) // $main),
     (str(.command) // ""),
     (str(.chrome) // ""),
     (if (.usageWarning | type) == "number" and .usageWarning >= 1 and .usageWarning <= 100 and .usageWarning == (.usageWarning | floor)
      then (.usageWarning | floor | tostring) else "80" end)
   ] | join("\u001f")),
  ($accounts | to_entries[] | .key as $name | .value as $v
   | (str($v.dir) | if . != null then expand_home
                      elif ($any_dir | not) and $name == $main then $master
                      else $base + "/" + $name end) as $dir
   | [ $name, (($v.email // "") | tostring | gsub("[\\n\\r\\u001f]"; " ")), $dir, (if $v.rc == true then "1" else "0" end) ] | join("\u001f"))
'

# Reads ~/.claude-accounts/accounts.json. Sets CFG_* and the ACC_* arrays (one index per account, file order).
load_accounts() {
    local file="$BASE_DIR/accounts.json" data head rest name email dir rc name_re='^[[:alnum:]_][[:alnum:]_.-]*$'
    CFG_MAIN=''; CFG_DEFAULT=''; CFG_PUBLISH=''; CFG_COMMAND=''; CFG_CHROME=''; CFG_WARN=80
    ACC_NAME=(); ACC_EMAIL=(); ACC_DIR=(); ACC_MASTER=(); ACC_RC=()
    if ! command -v jq >/dev/null 2>&1; then
        msg_red "jq not found: install it with 'brew install jq' (macOS) or with your distribution's package manager"
        return 1
    fi
    if [ ! -f "$file" ]; then msg_red "Missing $file (copy accounts.example.json and edit it)"; return 1; fi
    if ! data=$(jq -r --arg home "$HOME" --arg base "$BASE_DIR" --arg master "$MASTER_DIR" "$JQ_ACCOUNTS" "$file" 2>/dev/null); then
        msg_red "accounts.json is invalid or has no \"accounts\" object: $file"
        return 1
    fi
    case "$data" in
        *$'\n'*) head=${data%%$'\n'*}; rest=${data#*$'\n'} ;;
        *) head=$data; rest='' ;;
    esac
    IFS="$SEP" read -r CFG_MAIN CFG_DEFAULT CFG_PUBLISH CFG_COMMAND CFG_CHROME CFG_WARN <<EOF
$head
EOF
    [ -n "$CFG_MAIN" ] || { msg_red 'accounts.json has no "main"'; return 1; }
    CFG_COMMAND=${CFG_COMMAND:-cca}
    while IFS="$SEP" read -r name email dir rc; do
        [ -n "$name" ] || continue
        # The name becomes a folder name and a command argument: no slash, no space, no leading "." or "-".
        if ! [[ $name =~ $name_re ]]; then
            msg_red "Invalid account name: '$name' (use letters, digits, _ . - ; no spaces, and do not start with . or -)"
            return 1
        fi
        case "$name" in
            bin|rc|backups|*.sh|*.json|*.md|*.disabled)
                msg_red "Invalid account name: '$name' (it would collide with a file or folder of ~/.claude-accounts)"
                return 1 ;;
        esac
        case "$dir" in /*) ;; *) dir="$HOME/$dir" ;; esac
        while [ ${#dir} -gt 1 ] && [ "${dir%/}" != "$dir" ]; do dir=${dir%/}; done
        ACC_NAME[${#ACC_NAME[@]}]=$name
        ACC_EMAIL[${#ACC_EMAIL[@]}]=$email
        ACC_DIR[${#ACC_DIR[@]}]=$dir
        if [ "$dir" = "$MASTER_DIR" ]; then ACC_MASTER[${#ACC_MASTER[@]}]=1; else ACC_MASTER[${#ACC_MASTER[@]}]=0; fi
        ACC_RC[${#ACC_RC[@]}]=$rc
    done <<EOF
$rest
EOF
    [ ${#ACC_NAME[@]} -gt 0 ] || { msg_red 'accounts.json has no accounts under "accounts"'; return 1; }
    validate_accounts
}

# Rejects configurations that would make a script act on the wrong folder or on a missing account.
validate_accounts() {
    local i j dir
    for i in "${!ACC_NAME[@]}"; do
        dir=${ACC_DIR[$i]}
        case "/$dir/" in
            */../*|*/./*) msg_red "Invalid dir for account '${ACC_NAME[$i]}': $dir (no . or .. segments)"; return 1 ;;
        esac
        if [ "${ACC_MASTER[$i]}" != 1 ]; then
            case "$dir" in
                /|"$HOME"|"$MASTER_DIR"/*)
                    msg_red "Invalid dir for account '${ACC_NAME[$i]}': $dir (it must be its own folder, not your home, / or inside ~/.claude)"
                    return 1 ;;
            esac
        fi
        for j in "${!ACC_NAME[@]}"; do
            [ "$j" -lt "$i" ] && [ "${ACC_DIR[$j]}" = "$dir" ] && {
                msg_red "Accounts '${ACC_NAME[$j]}' and '${ACC_NAME[$i]}' use the same dir: $dir"; return 1; }
        done
    done
    account_exists "$CFG_DEFAULT" || { msg_red "\"default\" account '$CFG_DEFAULT' does not exist in accounts.json"; return 1; }
    account_exists "$CFG_PUBLISH" || { msg_red "\"publish\" account '$CFG_PUBLISH' does not exist in accounts.json"; return 1; }
    if [ -n "$CFG_CHROME" ] && ! account_exists "$CFG_CHROME"; then msg_red "\"chrome\" account '$CFG_CHROME' does not exist in accounts.json"; return 1; fi
    return 0
}

# E-mail addresses compare case-insensitively (the Windows version does too).
same_email() { [ "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" = "$(printf '%s' "$2" | tr '[:upper:]' '[:lower:]')" ]; }

# Sets A_NAME, A_EMAIL, A_DIR, A_MASTER (1/0) and A_RC (1/0) for the account with the given name.
select_account() {
    local i
    for i in "${!ACC_NAME[@]}"; do
        if [ "${ACC_NAME[$i]}" = "$1" ]; then
            A_NAME=${ACC_NAME[$i]}; A_EMAIL=${ACC_EMAIL[$i]}; A_DIR=${ACC_DIR[$i]}
            A_MASTER=${ACC_MASTER[$i]}; A_RC=${ACC_RC[$i]}
            return 0
        fi
    done
    return 1
}

account_exists() { local n; for n in "${ACC_NAME[@]}"; do [ "$n" = "$1" ] && return 0; done; return 1; }

# Account names joined by ", ".
accounts_list() { local n out=''; for n in "${ACC_NAME[@]}"; do out="${out:+$out, }$n"; done; printf '%s' "$out"; }

# ---------------------------------------------------------------- links (symlinks for files and folders)

# Makes sure the selected account has all its links. If a file link turned into a regular file (some
# programs save by writing a temp file and renaming it over the link), the newer version goes to the
# master folder before the link is recreated, so no change is lost. Prints one message per line.
sync_account_links() {
    [ "$A_MASTER" = 1 ] && return 0
    mkdir -p -- "$A_DIR" || return 1
    local stamp name target link backup state keys
    stamp=$(date +%Y%m%d_%H%M%S)

    for name in "${SHARED_FILES[@]}"; do
        target="$MASTER_DIR/$name"; link="$A_DIR/$name"
        [ -e "$target" ] || continue
        [ -L "$link" ] && continue
        if [ -e "$link" ]; then
            backup="$BASE_DIR/backups/relink_${A_NAME}_${stamp}_${name}"
            mkdir -p -- "$BASE_DIR/backups" || continue
            if [ "$link" -nt "$target" ]; then
                cp -p -- "$target" "$backup" && cp -p -- "$link" "$target" || { msg_red "could not preserve $link; left as is"; continue; }
                echo "${name}: change made in account $A_NAME was carried over to the master folder (previous version in $backup)"
            else
                cp -p -- "$link" "$backup" || { msg_red "could not back up $link; left as is"; continue; }
            fi
            rm -f -- "$link"
        fi
        if ln -s -- "$target" "$link"; then echo "link: $link"; else msg_red "could not create link $link"; fi
    done

    for name in "${SHARED_DIRS[@]}"; do
        target="$MASTER_DIR/$name"; link="$A_DIR/$name"
        [ -e "$target" ] || continue
        [ -L "$link" ] && continue
        if [ -e "$link" ]; then
            # Real folder created by Claude before the link existed: keep it under backups and link.
            backup="$BASE_DIR/backups/relink_${A_NAME}_${stamp}_${name}"
            mkdir -p -- "$BASE_DIR/backups" || continue
            mv -- "$link" "$backup" || { msg_red "could not move $link; left as is"; continue; }
            echo "${name}: local folder of account $A_NAME moved to $backup"
        fi
        if ln -s -- "$target" "$link"; then echo "link: $link"; else msg_red "could not create link $link"; fi
    done

    # Initial .claude.json: only the configuration keys of the master one, no account data.
    state="$A_DIR/.claude.json"
    if [ ! -e "$state" ] && [ -f "$MASTER_STATE" ]; then
        keys=$(printf '%s\n' "${SEED_KEYS[@]}" | jq -R . | jq -s -c .)
        if ( umask 077; jq --argjson ks "$keys" 'with_entries(select(.key as $k | $ks | index($k)))' "$MASTER_STATE" > "$state.tmp" ) 2>/dev/null \
           && mv -- "$state.tmp" "$state"; then
            echo "initial state: $state"
        else
            rm -f -- "$state.tmp"
            msg_yellow "could not create the initial .claude.json of $A_NAME (is $MASTER_STATE readable?)"
        fi
    fi
    return 0
}

# Removes only the links that point into the master folder (never its content).
remove_account_links() {
    [ "$A_MASTER" = 1 ] && return 0
    [ -d "$A_DIR" ] || return 0
    local f target
    for f in "$A_DIR"/* "$A_DIR"/.[!.]*; do
        [ -L "$f" ] || continue
        target=$(readlink "$f")
        case "$target" in "$MASTER_DIR"/*) rm -f -- "$f" ;; esac
    done
}

# Is there any link into the master folder inside the account folder?
account_has_links() {
    local f target
    for f in "$A_DIR"/* "$A_DIR"/.[!.]*; do
        [ -L "$f" ] || continue
        target=$(readlink "$f")
        case "$target" in "$MASTER_DIR"/*) return 0 ;; esac
    done
    return 1
}

# ---------------------------------------------------------------- running claude as an account

# run_claude args... : runs claude as the selected account. The master account runs without
# CLAUDE_CONFIG_DIR, otherwise Claude would look for .claude.json inside ~/.claude.
run_claude() {
    if [ "$A_MASTER" = 1 ]; then env -u CLAUDE_CONFIG_DIR "$CLAUDE" "$@"
    else env CLAUDE_CONFIG_DIR="$A_DIR" "$CLAUDE" "$@"; fi
}

# A command run from inside a Claude session (open-account.sh, "!" in the prompt) inherits the variables
# of that session; with CLAUDE_CODE_CHILD_SESSION the new session neither saves a transcript nor shows up
# in ListAgents. Drops only the variables that identify the parent session (never user configuration such
# as CLAUDE_CODE_USE_BEDROCK or CLAUDE_CODE_OAUTH_TOKEN) and never CLAUDE_CONFIG_DIR. Does nothing unless
# there is a sign of a parent session. Prints the names it removed.
clean_parent_session_env() {
    [ -n "${CLAUDECODE:-}${CLAUDE_CODE_CHILD_SESSION:-}${CLAUDE_CODE_SESSION_ID:-}" ] || return 0
    local name
    for name in $(compgen -e); do
        case "$name" in
            CLAUDECODE|CLAUDE_PID|CLAUDE_CODE_ENTRYPOINT|CLAUDE_CODE_CHILD_SESSION|CLAUDE_CODE_EXECPATH|CLAUDE_CODE_SSE_PORT|CLAUDE_CODE_SESSION_*|CLAUDE_CODE_MESSAGING_*)
                unset "$name"; echo "$name" ;;
        esac
    done
}

# Sets ST_LOGGED (1/0) and ST_EMAIL for the selected account. Fails if claude returns no JSON.
account_status() {
    local json
    ST_LOGGED=0; ST_EMAIL=''
    json=$(run_claude auth status --json 2>/dev/null) || true
    [ -n "$json" ] || return 1
    ST_LOGGED=$(printf '%s' "$json" | jq -r 'if .loggedIn == true then 1 else 0 end' 2>/dev/null) || { ST_LOGGED=0; return 1; }
    ST_EMAIL=$(printf '%s' "$json" | jq -r '.email // ""' 2>/dev/null)
    return 0
}

# ---------------------------------------------------------------- usage (5h and weekly windows)
# The account token is read from its .credentials.json in memory only: never copied, written, printed or
# refreshed here. macOS keeps the login in the Keychain (not in .credentials.json): there the usage comes
# from the last value Claude saved in the account .claude.json, as when a token has expired.

# date_fmt epoch format : formats in local time, with GNU date (Linux) or BSD date (macOS).
if date --version >/dev/null 2>&1; then
    date_fmt() { date -d "@$1" +"$2"; }      # GNU date
else
    date_fmt() { date -r "$1" +"$2"; }       # BSD date (macOS)
fi

state_file() { if [ "$A_MASTER" = 1 ]; then printf '%s' "$MASTER_STATE"; else printf '%s' "$A_DIR/.claude.json"; fi; }

# account_token [now_epoch] : prints the accessToken if it is still valid for more than 60 s; else nothing.
account_token() {
    local file="$A_DIR/.credentials.json" now=${1:-$(date +%s)} token
    [ -f "$file" ] || return 0
    token=$(jq -r --argjson now "$now" '
        .claudeAiOauth | select(.accessToken != null and (.expiresAt | tonumber) > (($now + 60) * 1000)) | .accessToken
    ' "$file" 2>/dev/null) || return 0
    # Token characters only: keeps anything odd out of the curl config.
    case "$token" in ''|*[!A-Za-z0-9._~+/=-]*) return 0 ;; esac
    printf '%s' "$token"
}

# usage_api token [timeout] : GET on the usage API. The token goes through curl's stdin (-K -), not the
# command line, so it does not show up in ps.
usage_api() {
    printf 'url = "https://api.anthropic.com/api/oauth/usage"\nheader = "Authorization: Bearer %s"\nheader = "anthropic-beta: oauth-2025-04-20"\n' "$1" \
        | curl -q -fsS -m "${2:-3}" -K - 2>/dev/null
}

usage_reset() { U_FIVE=''; U_WEEK=''; U_RESET_FIVE=''; U_RESET_WEEK=''; U_SOURCE=''; U_WHEN=''; }

# usage_convert json source when now : fills U_* (empty = unknown). A window that already reset counts as 0.
usage_convert() {
    local json=$1 source=$2 when=$3 now=$4 out
    usage_reset
    [ -n "$json" ] || return 0
    out=$(printf '%s' "$json" | jq -r --argjson now "$now" "$JQ_DEFS"'
        def window(k):
          (.[k]? ) as $w
          | if ($w | type) != "object" or $w.utilization == null then [null, null]
            else ($w.resets_at | ep) as $r
                 | if $r != null and $r <= $now then [0, null] else [($w.utilization | round), $r] end end;
        [window("five_hour"), window("seven_day")] as $j
        | [$j[0][0], $j[1][0], $j[0][1], $j[1][1]] | map(if . == null then "" else tostring end) | join("\u001f")
    ' 2>/dev/null) || return 0
    IFS="$SEP" read -r U_FIVE U_WEEK U_RESET_FIVE U_RESET_WEEK <<EOF
$out
EOF
    if [ -n "$U_FIVE$U_WEEK" ]; then U_SOURCE=$source; U_WHEN=$when; fi
    return 0
}

# account_usage [timeout] [now_epoch] : usage of the selected account, live if the token is valid, else saved.
account_usage() {
    local timeout=${1:-3} now=${2:-$(date +%s)} token json file cached ms
    usage_reset
    token=$(account_token "$now")
    if [ -n "$token" ]; then
        if json=$(usage_api "$token" "$timeout") && [ -n "$json" ]; then
            usage_convert "$json" live '' "$now"
            return 0
        fi
    fi
    file=$(state_file)
    if [ -f "$file" ]; then
        cached=$(jq -c '.cachedUsageUtilization // empty' "$file" 2>/dev/null)
        if [ -n "$cached" ]; then
            ms=$(printf '%s' "$cached" | jq -r '.fetchedAtMs // empty | floor' 2>/dev/null)
            usage_convert "$(printf '%s' "$cached" | jq -c '.utilization // empty' 2>/dev/null)" saved "${ms:+$((ms / 1000))}" "$now"
        fi
    fi
    return 0
}

# Highest percentage among the known windows (nothing if none).
max_usage() {
    local max=''
    [ -n "$U_FIVE" ] && max=$U_FIVE
    if [ -n "$U_WEEK" ] && { [ -z "$max" ] || [ "$U_WEEK" -gt "$max" ]; }; then max=$U_WEEK; fi
    printf '%s' "$max"
}

# "Session: x · Week: y", from the ready-made text of each window.
format_windows() { printf 'Session: %s · Week: %s' "$1" "$2"; }

# " (resets in 2h05)" until the window resets; empty when unknown or already past.
format_reset() {
    local reset=$1 now=${2:-$(date +%s)} min
    if [ -z "$reset" ] || [ "$reset" -le "$now" ]; then return 0; fi
    min=$(( (reset - now) / 60 ))
    if [ "$min" -lt 60 ]; then printf ' (resets in %dmin)' "$min"
    elif [ "$min" -lt 1440 ]; then printf ' (resets in %dh%02d)' $((min / 60)) $((min % 60))
    else printf ' (resets in %dd %dh)' $((min / 1440)) $(( (min % 1440) / 60 )); fi
}

# Text of the usage held in U_*.
format_usage() {
    local now=${1:-$(date +%s)} five week text
    if [ -z "$(max_usage)" ]; then printf '%s' '-'; return 0; fi
    if [ -z "$U_FIVE" ]; then five='?'; else five="$U_FIVE%$(format_reset "$U_RESET_FIVE" "$now")"; fi
    if [ -z "$U_WEEK" ]; then week='?'; else week="$U_WEEK%$(format_reset "$U_RESET_WEEK" "$now")"; fi
    text=$(format_windows "$five" "$week")
    if [ "$U_SOURCE" = saved ]; then
        # A value saved on another day carries the date, so it does not look like today's.
        if [ -z "$U_WHEN" ]; then text="$text (saved, no date)"
        elif [ "$(date_fmt "$U_WHEN" %Y%m%d)" = "$(date_fmt "$now" %Y%m%d)" ]; then text="$text (saved $(date_fmt "$U_WHEN" %H:%M))"
        else text="$text (saved $(date_fmt "$U_WHEN" '%d/%m %H:%M'))"; fi
    fi
    printf '%s' "$text"
}

# suggest_account exclude name=max ... : the account with the lowest max usage, except the excluded one;
# nothing if none has known usage.
suggest_account() {
    local exclude=$1 pair name max best='' best_max=''
    shift
    for pair in "$@"; do
        name=${pair%%=*}; max=${pair#*=}
        [ "$name" = "$exclude" ] && continue
        [ -n "$max" ] || continue
        if [ -z "$best_max" ] || [ "$max" -lt "$best_max" ]; then best=$name; best_max=$max; fi
    done
    printf '%s' "$best"
}

# ---------------------------------------------------------------- Remote Control per account
# settings.json is shared between accounts, so cc decides the RC of each session by passing --settings
# with a file from rc/ (the command line wins over the user's settings.json).

# split_rc_args args... : sets RC_ON (1/0), RC_USER_SETTINGS (1/0) and the RC_REST array. The default
# comes from the selected account. --no-rc is consumed; --rc [name] stays for claude itself.
split_rc_args() {
    local arg
    RC_ON=$A_RC; RC_USER_SETTINGS=0; RC_REST=()
    for arg in "$@"; do
        if [ "$arg" = '--no-rc' ]; then RC_ON=0; continue; fi
        if [ "$arg" = '--rc' ] || [ "$arg" = '--remote-control' ]; then RC_ON=1; fi
        if [ "$arg" = '--settings' ] || [ "${arg#--settings=}" != "$arg" ]; then RC_USER_SETTINGS=1; fi
        RC_REST[${#RC_REST[@]}]=$arg
    done
}

rc_file() {
    local name=off file
    [ "$1" = 1 ] && name=on
    file="$BASE_DIR/rc/$name.json"
    if [ ! -f "$file" ]; then
        mkdir -p -- "$BASE_DIR/rc"
        printf '{ "remoteControlAtStartup": %s }' "$([ "$1" = 1 ] && echo true || echo false)" > "$file"
    fi
    printf '%s' "$file"
}

# Sets CLAUDE_ARGS: the user's arguments plus the --settings with the RC decision (if the user passed
# their own --settings, it wins and we add none). Depends on split_rc_args.
build_claude_args() {
    CLAUDE_ARGS=("${RC_REST[@]}")
    if [ "$RC_USER_SETTINGS" != 1 ]; then
        CLAUDE_ARGS[${#CLAUDE_ARGS[@]}]='--settings'
        CLAUDE_ARGS[${#CLAUDE_ARGS[@]}]=$(rc_file "$RC_ON")
    fi
}

# ---------------------------------------------------------------- settings.json of the master folder

json_is_object() { printf '%s' "$1" | jq -e 'type == "object"' >/dev/null 2>&1; }

# Sets SET_FILE, SET_TEXT (byte for byte, so the user's file is not reformatted) and SET_VALID (1/0).
# A missing or empty file counts as {}. If the JSON is already broken, no function writes anything.
settings_read() {
    local text
    SET_FILE="$MASTER_DIR/settings.json"
    if [ -f "$SET_FILE" ]; then text=$(cat "$SET_FILE"; printf x); text=${text%x}; else text=''; fi
    case "$text" in *[![:space:]]*) ;; *) text='{}' ;; esac
    SET_TEXT=$text
    if json_is_object "$text"; then SET_VALID=1; else SET_VALID=0; fi
}

# Writes the text to settings.json (follows it if it is a symlink, instead of replacing it with a file).
settings_write() { mkdir -p -- "$MASTER_DIR" && printf '%s' "$1" > "$SET_FILE"; }

# Inserts a '"key": value' pair right after the first "{" of a JSON text, without reformatting the rest.
# Result in JSON_NEW. Fails if there is no object.
json_insert_first() {
    local text=$1 pair=$2 empty='^[[:space:]]*[{][[:space:]]*[}][[:space:]]*$'
    if [[ $text =~ $empty ]]; then JSON_NEW=$(printf '{\n  %s\n}\n' "$pair"; echo x); JSON_NEW=${JSON_NEW%x}; return 0; fi
    case "$text" in *'{'*) ;; *) return 1 ;; esac
    JSON_NEW="${text%%\{*}{"$'\n  '"$pair,${text#*\{}"
}

# Sessions opened without cc (claude directly, IDE, app) never turn RC on by themselves. Prints what it did.
disable_shared_rc() {
    local key='"remoteControlAtStartup"[[:space:]]*:[[:space:]]*' re_true re_false found msg new
    re_false="${key}false"; re_true="${key}true"
    settings_read
    if [ "$SET_VALID" != 1 ]; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    if [[ $SET_TEXT =~ $re_false ]]; then return 0; fi
    new=$SET_TEXT
    if [[ $new =~ $re_true ]]; then
        while [[ $new =~ $re_true ]]; do
            found=${BASH_REMATCH[0]}
            new="${new%%"$found"*}\"remoteControlAtStartup\": false${new#*"$found"}"
        done
        msg='settings.json: remoteControlAtStartup was true; now false (cc turns RC on only for accounts with rc or with --rc)'
    else
        json_insert_first "$new" '"remoteControlAtStartup": false' || { echo "$MSG_INVALID_SETTINGS"; return 0; }
        new=$JSON_NEW
        msg='settings.json: remoteControlAtStartup false written (RC only turns on through cc)'
    fi
    if ! json_is_object "$new"; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    settings_write "$new"
    echo "$msg"
}

# ---------------------------------------------------------------- status line: account and session usage

# Selects the account this session runs in (by CLAUDE_CONFIG_DIR). Fails if none matches.
current_account() {
    local i dir
    if [ -z "${CLAUDE_CONFIG_DIR:-}" ]; then
        for i in "${!ACC_NAME[@]}"; do [ "${ACC_MASTER[$i]}" = 1 ] && { select_account "${ACC_NAME[$i]}"; return $?; }; done
        return 1
    fi
    dir=${CLAUDE_CONFIG_DIR}
    while [ ${#dir} -gt 1 ] && [ "${dir%/}" != "$dir" ]; do dir=${dir%/}; done
    for i in "${!ACC_NAME[@]}"; do [ "${ACC_DIR[$i]}" = "$dir" ] && { select_account "${ACC_NAME[$i]}"; return $?; }; done
    return 1
}

# Percentage with color: yellow from the warning limit, red from 95%.
_pct_color() {
    local n=$1 warn=$2
    if [ "$n" = '?' ]; then printf '?'; return; fi
    if [ "$n" -ge 95 ]; then printf '\033[31m%s%%\033[0m' "$n"
    elif [ "$n" -ge "$warn" ]; then printf '\033[33m%s%%\033[0m' "$n"
    else printf '%s%%' "$n"; fi
}

# format_statusline account warn now < json : the status line (no trailing newline).
# Claude Code sends resets_at as Unix seconds.
format_statusline() {
    local account=$1 warn=${2:-80} now=${3:-$(date +%s)} data has p5 r5 p7 r7 five week parts
    data=$(jq -r "$JQ_DEFS"'
        (.rate_limits // null) as $rl
        | [ (if ($rl | type) == "object" and (($rl.five_hour | type) == "object" or ($rl.seven_day | type) == "object") then "1" else "0" end),
            (try (.rate_limits.five_hour.used_percentage | if . == null then "?" else round | tostring end) catch "?"),
            (try (.rate_limits.five_hour.resets_at | ep | if . == null then "" else tostring end) catch ""),
            (try (.rate_limits.seven_day.used_percentage | if . == null then "?" else round | tostring end) catch "?"),
            (try (.rate_limits.seven_day.resets_at | ep | if . == null then "" else tostring end) catch "")
          ] | join("\u001f")' 2>/dev/null) || return 1
    IFS="$SEP" read -r has p5 r5 p7 r7 <<EOF
$data
EOF
    parts=$account
    if [ "$has" = 1 ]; then
        five=$(_pct_color "$p5" "$warn")$(format_reset "$r5" "$now")
        week=$(_pct_color "$p7" "$warn")$(format_reset "$r7" "$now")
        parts="${parts:+$parts · }$(format_windows "$five" "$week")"
    fi
    printf '%s' "$parts"
}

# Registers our statusLine in settings.json, only if there is no other. Prints what it did.
register_statusline() {
    local cmd pair
    settings_read
    if [ "$SET_VALID" != 1 ]; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    case "$SET_TEXT" in
        *'"statusLine"'*)
            case "$SET_TEXT" in
                *"$MARK_STATUSLINE"*) return 0 ;;
                *) echo 'settings.json already has another statusLine: left untouched (the account and usage one stays unregistered)'; return 0 ;;
            esac ;;
    esac
    cmd=$(jq -n --arg c "\"$BASE_DIR/statusline.sh\"" '$c')
    pair="\"statusLine\": {\"type\": \"command\", \"command\": $cmd}"
    json_insert_first "$SET_TEXT" "$pair" || { echo "$MSG_INVALID_SETTINGS"; return 0; }
    if ! json_is_object "$JSON_NEW"; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    settings_write "$JSON_NEW"
    echo 'settings.json: statusLine registered (account and session usage)'
}

# Removes the statusLine if it is ours (the one pointing at .claude-accounts/statusline.sh); never another.
unregister_statusline() {
    local obj='"statusLine"[[:space:]]*:[[:space:]]*[{][^{}]*[.]claude-accounts/statusline[.]sh[^{}]*[}]'
    local re_after='^[[:space:]]*,[[:space:]]*' re_before=',[[:space:]]*$' found new before after
    settings_read
    if [ "$SET_VALID" != 1 ]; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    [[ $SET_TEXT =~ $obj ]] || return 0
    found=${BASH_REMATCH[0]}
    before=${SET_TEXT%%"$found"*}; after=${SET_TEXT#*"$found"}
    # With a comma after it (drop it), else a comma before it (it was the last key), else alone.
    if [[ $after =~ $re_after ]]; then after=${after#"${BASH_REMATCH[0]}"}
    elif [[ $before =~ $re_before ]]; then before=${before%"${BASH_REMATCH[0]}"}; fi
    new="$before$after"
    if ! json_is_object "$new"; then echo "$MSG_INVALID_SETTINGS"; return 0; fi
    settings_write "$new"
    echo 'settings.json: account and usage statusLine removed'
}

# ---------------------------------------------------------------- accounts block in ~/.claude/CLAUDE.md

# replace_all text marker value : replaces every occurrence of marker, without treating & or \ in value.
replace_all() {
    local text=$1 marker=$2 value=$3 out=''
    while [[ $text == *"$marker"* ]]; do out="$out${text%%"$marker"*}$value"; text=${text#*"$marker"}; done
    printf '%s' "$out$text"
}

# Path with ~ in place of HOME, for the CLAUDE.md text.
short_path() { case "$1" in "$HOME") printf '~' ;; "$HOME"/*) printf '~%s' "${1#"$HOME"}" ;; *) printf '%s' "$1" ;; esac; }

# block_bounds text : finds our block (END marker after BEGIN marker). Sets BLOCK_HEAD and BLOCK_TAIL, the text
# before and after it. Fails if there is no well-formed block.
block_bounds() {
    local rest
    [[ $1 == *"$MARK_BEGIN"* ]] || return 1
    rest=${1#*"$MARK_BEGIN"}
    [[ $rest == *"$MARK_END"* ]] || return 1
    BLOCK_HEAD=${1%%"$MARK_BEGIN"*}
    BLOCK_TAIL=${rest#*"$MARK_END"}
}

# Updates the block between the markers in ~/.claude/CLAUDE.md from CLAUDE.template.md.
update_claude_md() {
    local template table='' role i dir publish_email='' chrome block md current new
    template=$(cat "$BASE_DIR/CLAUDE.template.md") || return 1
    for i in "${!ACC_NAME[@]}"; do
        role=secondary; [ "${ACC_NAME[$i]}" = "$CFG_PUBLISH" ] && role=main
        if [ "${ACC_NAME[$i]}" = "$CFG_DEFAULT" ] && [ "$CFG_DEFAULT" != "$CFG_PUBLISH" ]; then role="$role, default of ${CFG_COMMAND}"; fi
        if [ "${ACC_MASTER[$i]}" = 1 ]; then dir='`~/.claude` (master folder)'; else dir="\`$(short_path "${ACC_DIR[$i]}")\`"; fi
        table="${table:+$table$'\n'}| ${ACC_NAME[$i]} | $role | ${ACC_EMAIL[$i]} | $dir |"
        [ "${ACC_NAME[$i]}" = "$CFG_PUBLISH" ] && publish_email=${ACC_EMAIL[$i]}
    done
    chrome='not set'
    for i in "${!ACC_NAME[@]}"; do
        [ -n "$CFG_CHROME" ] && [ "${ACC_NAME[$i]}" = "$CFG_CHROME" ] && chrome="\`${ACC_NAME[$i]}\` (${ACC_EMAIL[$i]})"
    done
    block=$(replace_all "$template" '{{TABLE}}' "$table")
    block=$(replace_all "$block" '{{PUBLISH}}' "$CFG_PUBLISH")
    block=$(replace_all "$block" '{{PUBLISH_EMAIL}}' "$publish_email")
    block=$(replace_all "$block" '{{COMMAND}}' "$CFG_COMMAND")
    block=$(replace_all "$block" '{{CHROME}}' "$chrome")
    block="$MARK_BEGIN"$'\n'"$block"$'\n'"$MARK_END"

    mkdir -p -- "$MASTER_DIR"
    md="$MASTER_DIR/CLAUDE.md"
    if [ -f "$md" ]; then current=$(cat "$md"); else current=''; fi
    if block_bounds "$current"; then
        new="$BLOCK_HEAD$block$BLOCK_TAIL"
    elif [[ $current == *[![:space:]]* ]]; then
        new="${current%"${current##*[![:space:]]}"}"$'\n\n'"$block"
    else
        new=$block
    fi
    printf '%s\n' "$new" > "$md"
}

remove_claude_md_block() {
    local md="$MASTER_DIR/CLAUDE.md" current new
    [ -f "$md" ] || return 0
    current=$(cat "$md")
    block_bounds "$current" || return 0
    new="$BLOCK_HEAD$BLOCK_TAIL"
    # Drop the blank lines around the removed block, but keep the indentation of the user's first line.
    while [[ $new == $'\n'* ]]; do new=${new#$'\n'}; done
    new=${new%"${new##*[![:space:]]}"}
    if [ -n "$new" ]; then printf '%s\n' "$new" > "$md"
    elif [ -L "$md" ]; then : > "$md"      # a symlinked CLAUDE.md (dotfiles) stays a link, just empty
    else rm -f -- "$md"; fi
}

# ---------------------------------------------------------------- text table (cc -l)

# print_table : reads lines of SEP-separated cells from stdin; the first line is the header.
# The last column must never be empty (read drops a trailing empty field).
print_table() {
    local lines=() line i n cells out rule first=1
    local widths=()
    while IFS= read -r line; do lines[${#lines[@]}]=$line; done
    for line in "${lines[@]}"; do
        IFS="$SEP" read -r -a cells <<< "$line"
        for i in "${!cells[@]}"; do
            n=${#cells[$i]}
            [ "$n" -gt "${widths[$i]:-0}" ] && widths[$i]=$n
        done
    done
    for line in "${lines[@]}"; do
        IFS="$SEP" read -r -a cells <<< "$line"
        out=''; rule=''
        for i in "${!cells[@]}"; do
            out="$out${cells[$i]}$(printf '%*s' $((widths[i] - ${#cells[$i]} + 2)) '')"
            rule="$rule$(printf '%*s' "${widths[$i]}" '' | tr ' ' '-')  "
        done
        printf '%s\n' "${out%"${out##*[![:space:]]}"}"
        if [ "$first" = 1 ]; then printf '%s\n' "${rule%"${rule##*[![:space:]]}"}"; first=0; fi
    done
}
